/**
 * Ответы терминала на запросы программы: отчёт о фокусе, атрибуты и версия терминала,
 * положение курсора, режимы, размер окна, цвета. xterm отправляет их программе тем же
 * путём, что и нажатия клавиш, но пользователь их не набирал.
 */
const TERMINAL_REPLY =
  /^(?:\x1b\[[IO]|\x1b\[[?>=]?[\d;]*(?:\$y|[cnRt])|\x1b\[\?[\d;]*u|\x1bP[\s\S]*?\x1b\\|\x1b\][\s\S]*?(?:\x07|\x1b\\))+$/

/** Ввод пришёл не от пользователя, а от самого терминала. */
export function isTerminalReply(data: string): boolean {
  return TERMINAL_REPLY.test(data)
}
